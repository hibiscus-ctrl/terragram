/** The draw.io style of a service's icon (a 1:1 vertex), or undefined when draw.io has no shape for the service. Fixed text: nothing in it comes from a document. */
export function drawioIconStyle(service: string): string | undefined {
  const aws = AWS[service];
  if (aws !== undefined) {
    return `outlineConnect=0;gradientColor=none;fillColor=${aws[1]};strokeColor=#ffffff;dashed=0;aspect=fixed;shape=mxgraph.aws4.resourceIcon;resIcon=mxgraph.aws4.${aws[0]};`;
  }
  const azure = AZURE[service];
  if (azure !== undefined) return `image;aspect=fixed;image=img/lib/azure2/${azure}.svg;`;
  const gcp = GCP[service];
  if (gcp !== undefined) return `aspect=fixed;strokeColor=none;fillColor=${gcp[1]};shape=mxgraph.gcp3.${gcp[0]};`;
  return undefined;
}
