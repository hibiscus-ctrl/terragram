import type { EvidenceReceipt } from "@/features/workspace/receipt";
import type { InfraModel } from "@/features/workspace/model";
import { resourceNodes } from "@/features/workspace/model";
import type { TerraformFile } from "@/features/workspace/terraform";

/**
 * What a Terragram change looks like on a Git host — pure, so the branch name,
 * commit and description can be checked without a network.
 *
 * The evidence travels with the code: the receipt is committed next to the plan, so
 * a reviewer on the pull request can download it and check it at /verify without
 * ever opening Terragram. The description carries the same hash the receipt does,
 * so the two cannot be quietly swapped.
 */

export type ChangeFile = { path: string; content: string };

/** A directory path with no leading or trailing slash; empty means the repo root. */
export function normaliseDirectory(input: string): string {
  const cleaned = input
    .trim()
    .replace(/\\/g, "/")
    .split("/")
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && s !== "." && s !== "..")
    .join("/");
  return cleaned;
}

function shortHash(contentHash: string): string {
  return contentHash.replace(/^sha256:/, "").slice(0, 10);
}

/** `terragram/2026-09-11-a1b2c3d4e5` — dated so two approvals never collide. */
export function branchName(receipt: Pick<EvidenceReceipt, "contentHash" | "approvedAt">): string {
  const day = receipt.approvedAt.slice(0, 10);
  return `terragram/${day}-${shortHash(receipt.contentHash)}`;
}

export function commitMessage(receipt: Pick<EvidenceReceipt, "contentHash" | "tool">): string {
  return `Add Terragram ${receipt.tool === "opentofu" ? "OpenTofu" : "Terraform"} plan (${shortHash(receipt.contentHash)})`;
}

export function changeTitle(model: InfraModel, receipt: Pick<EvidenceReceipt, "cloud">): string {
  const count = resourceNodes(model).length;
  const cloud = receipt.cloud === "aws" ? "AWS" : "Azure";
  return `Terragram: ${count} ${cloud} ${count === 1 ? "resource" : "resources"} for review`;
}

/** The files the change adds: the plan, then the receipt beside it. */
export function changeFiles(
  files: TerraformFile[],
  receipt: EvidenceReceipt,
  directory: string,
): ChangeFile[] {
  const dir = normaliseDirectory(directory);
  const at = (name: string) => (dir ? `${dir}/${name}` : name);
  return [
    ...files.map((f) => ({ path: at(f.name), content: f.content })),
    { path: at("terragram-receipt.json"), content: `${JSON.stringify(receipt, null, 2)}\n` },
  ];
}

export function changeBody(args: {
  model: InfraModel;
  receipt: EvidenceReceipt;
  files: ChangeFile[];
  verifyUrl: string;
}): string {
  const { receipt, model } = args;
  const resources = resourceNodes(model);
  const flagged = resources.filter((n) => n.flag);
  const lines = [
    "## What this is",
    "",
    receipt.explanation.trim(),
    "",
    "## Evidence",
    "",
    `- Content hash: \`${receipt.contentHash}\``,
    `- Signature: ${receipt.signed ? `Ed25519, key \`${receipt.keyId ?? "unnamed"}\`` : "unsigned (no signing key configured)"}`,
    `- Approved by: ${receipt.approver} at ${receipt.approvedAt}`,
    `- Generated by: ${receipt.engine === "managed" ? "managed inference (UK)" : "deterministic engine"} · ${receipt.tool} · ${receipt.regionLabel}`,
    "",
    `The receipt is committed alongside the plan. Download it with the plan files and check it at ${args.verifyUrl} — nothing is uploaded; the check runs in the browser.`,
    "",
    "## Files",
    "",
    ...args.files.map((f) => `- \`${f.path}\``),
    "",
    "## Resources",
    "",
    ...resources.map((n) => `- ${n.label} (\`${n.kind}\`)${n.flag ? " — **review flag**" : ""}`),
  ];
  if (flagged.length > 0) {
    lines.push(
      "",
      `> ${flagged.length} ${flagged.length === 1 ? "resource carries" : "resources carry"} a review flag the approver saw at the gate. Confirm ${flagged.length === 1 ? "it" : "them"} before merging.`,
    );
  }
  lines.push("", "_Terragram never applies infrastructure. Merging this is your decision._", "");
  return lines.join("\n");
}
