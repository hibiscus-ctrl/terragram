/**
 * The pure parts of scripts/refresh-azure-skus.mjs: reading allowed values out of the
 * azurerm documentation, turning Azure retail price rows into "this SKU is sold in this
 * region", and writing packages/engine/src/azure-sku-data.ts. Kept apart from the
 * script (which fetches as soon as it is imported) so tests can read them.
 */

const SOURCE_HEADER = `// Copyright 2026 Gabriel Ignat
// SPDX-License-Identifier: AGPL-3.0-only

`;

/** Lower-case, no spaces: how a region is written in Terraform ("UK South" is `uksouth`). */
export function regionKey(value) {
  return String(value).toLowerCase().replace(/\s+/g, "");
}

/**
 * The values a provider documentation page lists for one argument: every back-ticked
 * token on that argument's bullet (`* \`sku_name\` - (Required) ... \`B1\`, \`B2\` ...`),
 * minus the argument's own name. The page is untrusted text that ends up in a source
 * file, so a token is kept only when it is a plain SKU-shaped word.
 */
export function docValues(markdown, attribute) {
  const prefix = `* \`${attribute}\``;
  const line = markdown.split("\n").find((l) => l.startsWith(prefix));
  if (line === undefined) return [];
  const tokens = [...line.slice(prefix.length).matchAll(/`([^`]+)`/g)].map((m) => m[1]);
  return [...new Set(tokens)].filter((t) => /^[A-Za-z][A-Za-z0-9_]{0,63}$/.test(t));
}

/** `Standard` x `LRS, ZRS` -> `Standard_LRS`, `Standard_ZRS`; Premium has only LRS and ZRS. */
export function storageSkus(tiers, replications) {
  tiers = tiers.filter((t) => t === "Standard" || t === "Premium");
  const premium = new Set(["LRS", "ZRS"]);
  const out = [];
  for (const tier of tiers) {
    for (const replication of replications) {
      if (tier === "Premium" && !premium.has(replication)) continue;
      out.push(`${tier}_${replication}`);
    }
  }
  return out;
}

/** `P1 v3` / `I1mv2` / `B1` -> the azurerm `sku_name` of an App Service plan, or null. */
export function appServiceSku(skuName) {
  const compact = String(skuName).replace(/\s+/g, "");
  return /^[BDFIPS]\d{1,2}(?:m?v\d)?$/.test(compact) ? compact : null;
}

/** `Hot RA-GRS` -> `Standard_RAGRS`: the redundancies a general-purpose v2 account is sold in. */
export function storageSkuFromPrice(skuName) {
  const match = /^Hot ([A-Z-]+)$/.exec(String(skuName));
  return match ? `Standard_${match[1].replace(/-/g, "")}` : null;
}

/**
 * Fold price rows into `sku -> sorted regions`. `pick(row)` names the azurerm SKU a row
 * is the price of, or null for a row that is not one. Only an ordinary region name counts
 * (`uksouth`, as the price list spells it, not `Global`, `Intercontinental` or `Zone 1`).
 */
export function regionsBySku(rows, pick) {
  const bySku = new Map();
  for (const row of rows) {
    const sku = pick(row);
    const region = String(row.armRegionName ?? "");
    if (sku === null || !/^[a-z][a-z0-9]{2,40}$/.test(region)) continue;
    if (region === "global" || region === "intercontinental") continue;
    if (!bySku.has(sku)) bySku.set(sku, new Set());
    bySku.get(sku).add(region);
  }
  return new Map([...bySku].map(([sku, regions]) => [sku, [...regions].sort()]));
}

/**
 * Rule availability as `sets` (distinct lists of the regions that do NOT sell a SKU, out of
 * `allRegions`: a SKU is mostly sold nearly everywhere, so the short list is the gaps) and
 * `skus` (sku -> index into sets).
 */
export function packAvailability(bySku, allRegions) {
  const sets = [];
  const skus = {};
  for (const sku of [...bySku.keys()].sort()) {
    const sold = new Set(bySku.get(sku));
    const missing = allRegions.filter((r) => !sold.has(r));
    const key = missing.join(",");
    let index = sets.findIndex((s) => s.join(",") === key);
    if (index === -1) index = sets.push(missing) - 1;
    skus[sku] = index;
  }
  return { sets, skus };
}

/** JSON with two-space indent, but a list of plain words on one line (the region lists are long). */
function compactJson(data) {
  return JSON.stringify(data, null, 2).replace(/\[\n\s+("[^"\n]*"(?:,\n\s+"[^"\n]*")*)\n\s*\]/g, (_, items) => `[${items.replace(/,\n\s+/g, ", ")}]`);
}

/** The text of packages/engine/src/azure-sku-data.ts. `data` is plain JSON. */
export function renderSkuDataFile(data) {
  const json = compactJson(data);
  return `${SOURCE_HEADER}/**
 * Azure SKU names and the regions they are sold in, for the SKU check
 * (\`azure-sku.ts\`).
 *
 * GENERATED by \`npm run refresh:azure-skus\` — do not edit by hand. The values
 * come from two public sources, read once when this file is refreshed and never at
 * generate time, so the check is offline and deterministic:
 *
 *  - which SKU names are valid: the azurerm provider documentation at the tag in
 *    \`sources.docs\`;
 *  - which regions sell a SKU: Microsoft's public Azure Retail Prices API
 *    (\`sources.prices\`). A SKU with a price in a region is sold there. This is the
 *    price list, not the subscription-level Resource SKUs API: it does not know about
 *    capacity limits or restrictions on a given subscription, so "not sold here" is a
 *    reason to look, not proof that an apply fails.
 *
 * Only the resource types Terragram emits are here.
 */

export type SkuRuleData = {
  /** SKU names the provider documents (matched ignoring case). */
  valid: string[];
  /** For a family documented as a pattern rather than a list (the database SKUs). */
  pattern?: string;
  /** Where each SKU is not sold: \`skus\` maps a SKU to an index into \`sets\`, each a list of regions (out of \`regions\`) with no price for it. Absent when there is no region data. */
  available?: { sets: string[][]; skus: Record<string, number> };
};

export type AzureSkuData = {
  /** When the file was refreshed (ISO date). */
  refreshed: string;
  sources: { docs: string; prices: string };
  /** Every region the price list names, as written in Terraform (\`uksouth\`). */
  regions: string[];
  rules: Record<string, SkuRuleData>;
};

export const AZURE_SKU_DATA: AzureSkuData = ${json};
`;
}
