/**
 * The pure parts of scripts/refresh-providers.mjs: choosing the newest release on a
 * line, and the per-file header the generated sources carry. Kept apart from the
 * script (which fetches from the registry as soon as it is imported) so tests can
 * read them.
 */

/**
 * The header every source file in the repository carries. The generated
 * provider-versions.ts and module-versions.ts start with it, so `reuse lint` and a
 * reader see the same licence on them as on the files written by hand.
 */
const SOURCE_HEADER = `// Copyright 2026 Gabriel Ignat
// SPDX-License-Identifier: AGPL-3.0-only

`;

/** Only a plain MAJOR.MINOR.PATCH is a version; the whole string must match. */
const PLAIN_VERSION = /^(0|[1-9]\d{0,8})\.(0|[1-9]\d{0,8})\.(0|[1-9]\d{0,8})$/;

/**
 * The newest of these versions on the line `pin` is on, final releases only. The registry
 * response is untrusted input that is written into a TypeScript source file, so a string
 * is a candidate only when it is exactly `MAJOR.MINOR.PATCH`: a fourth segment, a
 * pre-release or build suffix, or anything else is ignored. The line is the major
 * version, or for a 0.x release the minor version too: semver lets a 0.x minor release
 * break its inputs, and most Azure Verified Modules are 0.x.
 */
export function newestOnLine(source, versions, pin) {
  const [pinMajor, pinMinor] = pin.split(".").map(Number);
  const final = versions
    .map((v) => (typeof v === "string" ? PLAIN_VERSION.exec(v) : null))
    .filter((m) => m !== null)
    .map((m) => ({ text: m[0], parts: [Number(m[1]), Number(m[2]), Number(m[3])] }))
    .filter(({ parts: [major, minor] }) => major === pinMajor && (pinMajor !== 0 || minor === pinMinor))
    .sort((a, b) => a.parts[1] - b.parts[1] || a.parts[2] - b.parts[2]);
  const found = final.at(-1);
  if (!found) throw new Error(`${source}: no release on the ${pin} line on the registry`);
  return found.text;
}

/** The text of packages/engine/src/provider-versions.ts for these resolved providers. */
export function renderProviderFile(date, resolved) {
  const entries = resolved
    .map(
      (p) =>
        `  ${p.cloud}: {\n    name: "${p.name}",\n    source: "${p.source}",\n    version: "${p.constraint}",\n  },`,
    )
    .join("\n");
  return `${SOURCE_HEADER}/**
 * Provider version constraints used by the Terraform emitter.
 *
 * GENERATED by \`npm run refresh:providers\` — do not edit by hand. Refreshed
 * ${date} against registry.terraform.io. The emitter reads this file so that
 * generated plans pin a current provider without the request path ever touching
 * the network.
 */

export type ProviderPin = { name: string; source: string; version: string };

export const PROVIDER_VERSIONS: Record<"azure" | "aws", ProviderPin> = {
${entries}
};

/** When the pins above were last refreshed (ISO date). Data for hosts and tooling to read, not used by the engine itself. @public */
export const PROVIDER_VERSIONS_REFRESHED = "${date}";
`;
}

/** The text of packages/engine/src/module-versions.ts for these resolved module pins. */
export function renderModuleFile(date, modulePins) {
  const moduleEntries = modulePins
    .map((m) => `  "${m.key}": { source: "${m.source}", version: "${m.version}" },`)
    .join("\n");
  return `${SOURCE_HEADER}/**
 * Registry module pins used by the Terraform emitter.
 *
 * GENERATED by \`npm run refresh:providers\` — do not edit by hand. Refreshed
 * ${date} against registry.terraform.io. Modules are pinned to an EXACT version,
 * unlike providers: a module call is code Terragram did not write, and the evidence
 * receipt records which code, so \`~>\` would make the receipt say less than it
 * should. The emitter reads this file so the request path never touches the network.
 */

export type ModulePin = { source: string; version: string };

export const MODULE_VERSIONS = {
${moduleEntries}
} as const satisfies Record<string, ModulePin>;

export type ModuleKey = keyof typeof MODULE_VERSIONS;

/** When the pins above were last refreshed (ISO date). Data for hosts and tooling to read, not used by the engine itself. @public */
export const MODULE_VERSIONS_REFRESHED = "${date}";
`;
}
