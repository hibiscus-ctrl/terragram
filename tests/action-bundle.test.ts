import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { builtinModules } from "node:module";
import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, it } from "node:test";
import { fileURLToPath } from "node:url";

/**
 * What a workflow actually runs is the committed `action/dist/index.mjs`, so the tests
 * hold the file itself to account: it is what the source builds to, it imports nothing
 * the runner would have to install, and the source reaches the engine only through its
 * public exports.
 */

const root = fileURLToPath(new URL("..", import.meta.url));
const scratch = mkdtempSync(join(tmpdir(), "terragram-action-bundle-"));
after(() => rmSync(scratch, { recursive: true, force: true }));

const committed = readFileSync(join(root, "action/dist/index.mjs"), "utf8");

function importSpecifiers(source: string): string[] {
  const found = new Set<string>();
  const patterns = [
    /^\s*(?:import|export)\b[^"'`;]*?\bfrom\s*["']([^"']+)["']/gm,
    /^\s*import\s*["']([^"']+)["']/gm,
    /\bimport\s*\(\s*["']([^"']+)["']\s*\)/g,
    /\brequire\s*\(\s*["']([^"']+)["']\s*\)/g,
  ];
  for (const pattern of patterns) for (const m of source.matchAll(pattern)) found.add(m[1] ?? "");
  return [...found];
}

describe("action/dist/index.mjs", () => {
  it("is exactly what `npm run build:action` produces from the source in this checkout", () => {
    const rebuilt = join(scratch, "index.mjs");
    execFileSync(process.execPath, [join(root, "action/build.mjs"), "--outfile", rebuilt], { cwd: root, stdio: "pipe" });
    assert.ok(
      readFileSync(rebuilt, "utf8") === committed,
      "action/dist is stale: run `npm run build:action` and commit the result",
    );
  });

  it("imports nothing but Node's own modules: no @infraweaver-io, no zod, no node_modules", () => {
    const specifiers = importSpecifiers(committed);
    assert.ok(specifiers.length > 0, "the scan found no imports at all, so it proves nothing");
    assert.deepEqual(
      specifiers.filter((s) => !(s.startsWith("node:") || builtinModules.includes(s))),
      [],
    );
    assert.equal(committed.includes("@infraweaver-io"), false);
  });

  it("starts with the licence line and says it is generated", () => {
    const [first, second] = committed.split("\n");
    // REUSE-IgnoreStart
    assert.equal(first, "// SPDX-License-Identifier: AGPL-3.0-only");
    // REUSE-IgnoreEnd
    assert.match(second ?? "", /^\/\/ Generated by action\/build\.mjs/);
  });
});

describe("the Action's source", () => {
  it("reaches the engine only through its public exports, and nothing else from npm", () => {
    const engine = JSON.parse(readFileSync(join(root, "packages/engine/package.json"), "utf8")) as {
      exports: Record<string, string>;
    };
    const exported = new Set(Object.keys(engine.exports).map((key) => `terragram-engine/${key.slice(2)}`));
    const dir = join(root, "action/src");
    const files = readdirSync(dir).filter((name) => name.endsWith(".ts"));
    assert.ok(files.length > 5);
    for (const file of files) {
      for (const specifier of importSpecifiers(readFileSync(join(dir, file), "utf8"))) {
        if (specifier.startsWith(".")) continue;
        if (specifier.startsWith("node:")) continue;
        assert.ok(exported.has(specifier), `${file} imports ${specifier}, which is not a public export of the engine`);
      }
    }
  });
});

describe("action.yml", () => {
  const manifest = readFileSync(join(root, "action/action.yml"), "utf8");

  /** The top-level keys under `section:`, and the lines of each one's block. */
  function section(name: string): Map<string, string[]> {
    const lines = manifest.split("\n");
    const start = lines.indexOf(`${name}:`);
    assert.ok(start >= 0, `no ${name}: section`);
    const blocks = new Map<string, string[]>();
    let current: string[] = [];
    for (const line of lines.slice(start + 1)) {
      if (line !== "" && !line.startsWith(" ")) break;
      const key = /^ {2}([a-z-]+):\s*$/.exec(line)?.[1];
      if (key) {
        current = [];
        blocks.set(key, current);
      } else {
        current.push(line);
      }
    }
    return blocks;
  }
  const defaultOf = (lines: string[] | undefined) => lines?.map((l) => /^ {4}default:\s*(.+)$/.exec(l)?.[1]).find(Boolean);

  it("runs the committed bundle on node24", () => {
    assert.match(manifest, /^runs:\n {2}using: node24\n {2}main: dist\/index\.mjs\n/m);
  });

  it("declares the inputs and outputs the code reads and writes, with the documented defaults", () => {
    assert.deepEqual([...section("outputs").keys()].sort(), ["changed", "content-hash", "receipt-path", "snapshot-id"]);
    const inputs = section("inputs");
    assert.deepEqual([...inputs.keys()].sort(), [
      "comment",
      "control-plane-audience",
      "control-plane-url",
      "github-token",
      "mode",
      "model",
      "signing-key",
      "terraform-dir",
    ]);
    assert.equal(defaultOf(inputs.get("model")), "diagram.json");
    assert.equal(defaultOf(inputs.get("terraform-dir")), "infra/");
    assert.equal(defaultOf(inputs.get("mode")), "check");
    assert.equal(defaultOf(inputs.get("comment")), '"true"');
    assert.equal(defaultOf(inputs.get("github-token")), "${{ github.token }}");
    assert.equal(defaultOf(inputs.get("signing-key")), undefined);
    assert.equal(defaultOf(inputs.get("control-plane-audience")), "infraharvest-api");
    assert.equal(defaultOf(inputs.get("control-plane-url")), undefined);
    for (const [name, lines] of inputs) assert.ok(!lines.includes("    required: true"), `${name} must be optional`);
  });
});
