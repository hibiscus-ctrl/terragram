/**
 * Bundle the Action into one file, `dist/index.mjs`, with the engine, zod and dagre
 * inside it. Nothing is left external, so `node dist/index.mjs` runs on a bare runner:
 * no `npm ci`, no registry, and no `@infraweaver-io/*` import left to resolve.
 *
 * The bundle is committed (a JavaScript Action runs from the checked-out repository),
 * so it is not minified: it is what a user is asked to pin and trust, and a diff of it
 * should be readable. CI rebuilds it and fails when the committed file differs.
 *
 * `--outfile <path>` writes elsewhere, for the tests that build without touching dist/.
 */

import { mkdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";

import { build } from "esbuild";

const root = import.meta.dirname;
const { values } = parseArgs({ options: { outfile: { type: "string" } } });
const outfile = values.outfile ? resolve(values.outfile) : join(root, "dist", "index.mjs");
mkdirSync(dirname(outfile), { recursive: true });

await build({
  absWorkingDir: root,
  entryPoints: ["src/main.ts"],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node24",
  // Third-party licence notices (zod, dagre) stay in the file, at the end.
  legalComments: "eof",
  // Bundled CommonJS (dagre) reaches for `require`, which an ES module lacks.
  banner: {
    js: [
// REUSE-IgnoreStart
      "// SPDX-License-Identifier: AGPL-3.0-only",
// REUSE-IgnoreEnd
      "// Generated by action/build.mjs from action/src and packages/engine. Do not edit.",
      'import { createRequire as __createRequire } from "node:module";',
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "warning",
});

console.log(`index.mjs: ${(statSync(outfile).size / 1024).toFixed(0)} KiB`);
